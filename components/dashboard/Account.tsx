"use client";
import { useState } from "react";
import { Coins, CreditCard, FolderOpen, LifeBuoy, Settings } from "lucide-react";
import data from "@/lib/account.json";
const B = data.balance;
import { Choice, DemoTag, GRADS, ToolHeader } from "./tool-ui";

const Note = ({ t }: { t: string }) => <p role="status" className="mt-3 min-h-[1.25rem] text-sm text-muted">{t}</p>;
const Title = ({ children }: { children: React.ReactNode }) => <h2 className="mb-4 text-xl font-bold">{children}</h2>;

export function Creations() {
  const [f, setF] = useState("All"), [q, setQ] = useState(""), [note, setNote] = useState("");
  const items = data.creations.filter((c) => (f === "All" || c.k === f) && c.t.toLowerCase().includes(q.toLowerCase()));
  return (
    <div className="mx-auto max-w-6xl">
      <ToolHeader Icon={FolderOpen} title="My Creations" desc="All your generated images, videos, voices and scripts in one place." note="these are sample creations. Nothing here was generated by AI." />
      <div className="mb-5 flex flex-wrap items-end gap-4">
        <div><label htmlFor="cs" className="sr-only">Search creations</label><input id="cs" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search creations…" className="field !w-64" /></div>
        <Choice label="Type" options={["All", "Image", "Video", "Voice", "Script"] as const} value={f as "All"} onChange={setF} />
      </div>
      {items.length ? (
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          {items.map((c) => (
            <article key={c.t} className="overflow-hidden rounded-2xl border border-line bg-card">
              <div className={`relative h-32 bg-gradient-to-br ${GRADS[c.g]}`}><div className="absolute left-3 top-3"><DemoTag /></div></div>
              <div className="p-4"><h3 className="font-semibold">{c.t}</h3><p className="text-sm text-muted">{c.k} · {c.d}</p>
                <div className="mt-3 flex gap-4 text-sm font-semibold"><button type="button" onClick={() => setNote("Demo only: Download is a placeholder.")} className="text-brand">Download</button><button type="button" onClick={() => setNote("Demo only: Delete is a placeholder.")} className="text-muted">Delete</button></div></div>
            </article>
          ))}
        </div>
      ) : <div className="grid min-h-[200px] place-items-center rounded-3xl border border-dashed border-line bg-card text-muted">No creations match.</div>}
      <Note t={note} />
    </div>
  );
}

