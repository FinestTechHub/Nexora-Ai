function Switch({ label, desc, on, set }: { label: string; desc: string; on: boolean; set: (v: boolean) => void }) {
  return (
    <div className="flex items-center justify-between gap-4 py-3"><div><b>{label}</b><p className="text-sm text-muted">{desc}</p></div>
      <button type="button" role="switch" aria-checked={on} aria-label={label} onClick={() => set(!on)} className={`relative h-[26px] w-[46px] shrink-0 rounded-full transition ${on ? "bg-brand" : "bg-line"}`}><span className={`absolute top-[3px] h-5 w-5 rounded-full bg-white transition-all ${on ? "left-[23px]" : "left-[3px]"}`} /></button></div>
  );
}

